export function t(lang, key, params) {
  const dict = MESSAGES[lang] || MESSAGES.en;
  let text = dict[key] ?? MESSAGES.en[key] ?? key;
  if (params) {
    for (const name of Object.keys(params)) {
      text = text.split("{" + name + "}").join(String(params[name]));
    }
  }
  return text;
}
